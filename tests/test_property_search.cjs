const assert=require('node:assert/strict');
const s=require('../js/property-search.js');
const parsed=s.parse('apartamento em Santos 2 quartos até R$ 500 mil');
assert.equal(parsed.cidade,'Santos'); assert.equal(parsed.tipo,'apartamento'); assert.equal(parsed.quartos,'2'); assert.equal(parsed.preco_max,500000); assert.deepEqual(parsed.terms,[]);
for(const [text,n] of [['R$ 1.250.000,50',1250000.5],['1,5 milhão',1500000],['1.5 mi',1500000],['500 mil',500000],['700.000',700000],['500',500]]) assert.equal(s.money(text),n,text);
for(const city of s.cities) assert.equal(s.parse(s.normalize(city)).cidade,city);
assert.equal(s.parse('casa em Riviera de São Lourenço').cidade,'Bertioga');
assert.equal(s.parse('casa com 12 quartos').quartos,'12');
const p={title:'Apartamento vista mar',city:'Santos',type:'Venda',price:'R$ 450.000,00',bedrooms:'2',tags:['Vista mar']};
assert.equal(s.matches(p,parsed),true);
assert.equal(s.matches({...p,price:'R$ 600.000'},parsed),false);
assert.equal(s.matches({...p,city:'Bertioga'},parsed),false);
assert.equal(s.matches({...p,bedrooms:1},parsed),false);
assert.equal(s.matches(p,s.parse('casa em Santos')),false);
assert.equal(s.matches(p,s.parse('apartamento piscina')),false);
assert.equal(s.matches(p,s.parse('apartamento vista mar')),true);
assert.equal(s.matches(p,s.parse('temporada')),false);
assert.equal(s.matches(p,s.parse('')),true);
let explicit=s.fromParams(new URLSearchParams('q=casa+em+Santos&cidade=Bertioga&tipo=apartamento&preco_max=500000'));
assert.equal(explicit.cidade,'Bertioga');assert.equal(explicit.tipo,'apartamento');
assert.equal(s.fromParams(new URLSearchParams('q=Santos&cidade=')).cidade,'');
assert.equal(s.fromParams(new URLSearchParams('preco_max=nope')).preco_max,'');
assert.equal(s.matches(p,s.fromParams(new URLSearchParams('tipo=%5B'))),false);
assert.deepEqual(s.parse('<script>alert(1)</script>').terms,['script','alert','1','script']);
console.log('Property search: 39 parser/filter assertions passed');
